"""
Report Generator
================
Generates plain-text and CSV reports from a completed threat assessment.
"""

import csv
import io
from typing import List, Dict, Any


def generate_text_report(
    system: Dict[str, Any],
    threats: List[Dict[str, Any]],
    summary: Dict[str, Any],
) -> str:
    """Return a human-readable plain-text threat report."""
    lines: List[str] = []

    lines.append("=" * 72)
    lines.append("  STRIDE THREAT MODEL REPORT")
    lines.append("=" * 72)
    lines.append("")

    lines.append(f"System Name   : {system.get('name', 'N/A')}")
    lines.append(f"Description   : {system.get('description', 'N/A')}")
    lines.append("")

    # Components
    lines.append("-" * 72)
    lines.append("COMPONENTS")
    lines.append("-" * 72)
    for comp in system.get("components", []):
        lines.append(f"  [{comp.get('type','').upper()}] {comp.get('name','')} — {comp.get('description','')}")
    lines.append("")

    # Data Flows
    lines.append("-" * 72)
    lines.append("DATA FLOWS")
    lines.append("-" * 72)
    for df in system.get("data_flows", []):
        lines.append(
            f"  {df.get('from','')} --> {df.get('to','')} : {df.get('label','')} ({df.get('protocol','')})"
        )
    lines.append("")

    # Trust Boundaries
    lines.append("-" * 72)
    lines.append("TRUST BOUNDARIES")
    lines.append("-" * 72)
    for tb in system.get("trust_boundaries", []):
        lines.append(f"  {tb.get('name','')} — {tb.get('description','')}")
    lines.append("")

    # Summary
    lines.append("-" * 72)
    lines.append("THREAT SUMMARY")
    lines.append("-" * 72)
    rc = summary.get("risk_counts", {})
    lines.append(f"  Total Threats Identified : {summary.get('total_threats', 0)}")
    lines.append(f"  High Risk                : {rc.get('High', 0)}")
    lines.append(f"  Medium Risk              : {rc.get('Medium', 0)}")
    lines.append(f"  Low Risk                 : {rc.get('Low', 0)}")
    lines.append(f"  Highest Risk Category    : {summary.get('highest_risk_category', 'N/A')}")
    lines.append("")

    # Threats
    lines.append("-" * 72)
    lines.append("IDENTIFIED THREATS")
    lines.append("-" * 72)
    for t in threats:
        lines.append("")
        lines.append(f"  ID          : {t.get('id','')}")
        lines.append(f"  Name        : {t.get('name','')}")
        lines.append(f"  Category    : {t.get('category','')}")
        lines.append(f"  Affected    : {', '.join(t.get('affected_components', []))}")
        lines.append(f"  Description : {t.get('description','')}")
        lines.append(f"  Likelihood  : {t.get('likelihood','')}")
        lines.append(f"  Impact      : {t.get('impact','')}")
        lines.append(f"  Risk Level  : {t.get('risk_level','')}")
        lines.append(f"  Mitigation  : {t.get('mitigation','')}")
        lines.append(f"  Control     : {t.get('security_control','')}")
        lines.append("  " + "-" * 68)

    lines.append("")
    lines.append("=" * 72)
    lines.append("  END OF REPORT — Generated by STRIDE Threat Model Analyzer")
    lines.append("=" * 72)

    return "\n".join(lines)


def generate_csv_report(
    system: Dict[str, Any],
    threats: List[Dict[str, Any]],
) -> str:
    """Return a CSV string containing one row per identified threat."""
    output = io.StringIO()
    writer = csv.writer(output)

    writer.writerow([
        "System Name", "ID", "Threat Name", "STRIDE Category",
        "Affected Components", "Description",
        "Likelihood", "Impact", "Risk Level",
        "Recommended Mitigation", "Security Control",
    ])

    system_name = system.get("name", "N/A")
    for t in threats:
        writer.writerow([
            system_name,
            t.get("id", ""),
            t.get("name", ""),
            t.get("category", ""),
            "; ".join(t.get("affected_components", [])),
            t.get("description", ""),
            t.get("likelihood", ""),
            t.get("impact", ""),
            t.get("risk_level", ""),
            t.get("mitigation", ""),
            t.get("security_control", ""),
        ])

    return output.getvalue()
